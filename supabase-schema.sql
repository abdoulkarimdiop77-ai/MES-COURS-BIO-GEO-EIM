-- 1. TABLE DES CLASSES
CREATE TABLE IF NOT EXISTS public.classes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom TEXT NOT NULL,
    niveau TEXT DEFAULT '11ème',
    effectif TEXT DEFAULT '',
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- 2. TABLE DES ÉLÈVES
CREATE TABLE IF NOT EXISTS public.eleves (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom TEXT NOT NULL,
    classe_id BIGINT REFERENCES public.classes(id) ON DELETE CASCADE,
    num TEXT DEFAULT '',
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- 3. TABLE DES COURS / CHAPITRES
CREATE TABLE IF NOT EXISTS public.cours (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titre TEXT NOT NULL,
    mat TEXT NOT NULL, -- 'Biologie' ou 'Géologie'
    classe_id BIGINT REFERENCES public.classes(id) ON DELETE CASCADE,
    debut TEXT DEFAULT '',
    statut TEXT DEFAULT 'Planifié', -- 'En cours', 'Terminé', 'Planifié'
    obj TEXT DEFAULT '',
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- 4. TABLE DES NOTES & ÉVALUATIONS
CREATE TABLE IF NOT EXISTS public.notes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titre TEXT NOT NULL,
    mat TEXT NOT NULL,
    classe_id BIGINT REFERENCES public.classes(id) ON DELETE CASCADE,
    eleve_id BIGINT REFERENCES public.eleves(id) ON DELETE CASCADE,
    date TEXT DEFAULT '',
    bareme NUMERIC DEFAULT 20,
    note NUMERIC NOT NULL,
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- 5. TABLE DES RESSOURCES PÉDAGOGIQUES
CREATE TABLE IF NOT EXISTS public.ressources (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titre TEXT NOT NULL,
    type TEXT DEFAULT 'Document', -- 'Cours', 'Exercice', 'Corrigé', 'Évaluation', 'Schéma', 'Document'
    mat TEXT DEFAULT 'Biologie',
    classe_id BIGINT REFERENCES public.classes(id) ON DELETE SET NULL,
    desc_txt TEXT DEFAULT '',
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- 6. TABLE DE L'EMPLOI DU TEMPS (CRÉNEAUX / SLOTS)
CREATE TABLE IF NOT EXISTS public.edt_slots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    jour TEXT NOT NULL, -- 'Lundi', 'Mardi', ...
    hdeb TEXT NOT NULL, -- '07h00', ...
    hfin TEXT NOT NULL, -- '08h00', ...
    mat TEXT NOT NULL,  -- 'Biologie' ou 'Géologie'
    classe TEXT NOT NULL,
    lecon TEXT DEFAULT '',
    salle TEXT DEFAULT '',
    span INTEGER DEFAULT 1,
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- 7. TABLE DE L'HISTORIQUE DES RAPPELS
CREATE TABLE IF NOT EXISTS public.rappels (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date TEXT NOT NULL,
    mat TEXT NOT NULL,
    classe TEXT NOT NULL,
    lecon TEXT DEFAULT '',
    canal TEXT DEFAULT 'Navigateur', -- 'Email' ou 'Navigateur'
    ok BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- 8. TABLE DE CONFIGURATION DE L'APPLICATION (EmailJS & Préférences)
CREATE TABLE IF NOT EXISTS public.app_config (
    id TEXT PRIMARY KEY DEFAULT 'general',
    email TEXT DEFAULT 'abdoulkarimdiop77@gmail.com',
    ejs_service TEXT DEFAULT '',
    ejs_template TEXT DEFAULT '',
    ejs_pub_key TEXT DEFAULT '',
    updated_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

