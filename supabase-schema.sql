-- ==============================================================================
-- SCHÉMA DE BASE DE DONNÉES SUPABASE POUR MES-COURS-BIO-GEO-EIM (VERSION ÉTENDUE)
-- Gestion des cours, classes, présences, devoirs en ligne, cahier journal et notes
-- ==============================================================================

-- 1. TABLE DES CLASSES
CREATE TABLE IF NOT EXISTS public.classes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom TEXT NOT NULL,
    niveau TEXT DEFAULT '7ème',
    cycle TEXT DEFAULT 'Collège', -- 'Collège', 'Lycée', 'Supérieur'
    effectif TEXT DEFAULT '',
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);
ALTER TABLE public.classes ADD COLUMN IF NOT EXISTS cycle TEXT DEFAULT 'Collège';

-- 2. TABLE DES ÉLÈVES
CREATE TABLE IF NOT EXISTS public.eleves (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom TEXT NOT NULL,
    classe_id BIGINT REFERENCES public.classes(id) ON DELETE CASCADE,
    num TEXT DEFAULT '',
    matricule TEXT DEFAULT '',
    photo TEXT DEFAULT '',
    observations TEXT DEFAULT '',
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);
ALTER TABLE public.eleves ADD COLUMN IF NOT EXISTS matricule TEXT DEFAULT '';
ALTER TABLE public.eleves ADD COLUMN IF NOT EXISTS photo TEXT DEFAULT '';
ALTER TABLE public.eleves ADD COLUMN IF NOT EXISTS observations TEXT DEFAULT '';

-- 3. TABLE DES COURS / CHAPITRES
CREATE TABLE IF NOT EXISTS public.cours (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titre TEXT NOT NULL,
    mat TEXT NOT NULL,
    classe_id BIGINT REFERENCES public.classes(id) ON DELETE CASCADE,
    debut TEXT DEFAULT '',
    statut TEXT DEFAULT 'Planifié', -- 'En cours', 'Terminé', 'Planifié'
    obj TEXT DEFAULT '',
    contenu TEXT DEFAULT '',
    url_drive TEXT DEFAULT '',
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);
ALTER TABLE public.cours ADD COLUMN IF NOT EXISTS contenu TEXT DEFAULT '';
ALTER TABLE public.cours ADD COLUMN IF NOT EXISTS url_drive TEXT DEFAULT '';

-- 4. TABLE DES NOTES & ÉVALUATIONS
CREATE TABLE IF NOT EXISTS public.notes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titre TEXT NOT NULL,
    mat TEXT NOT NULL,
    classe_id BIGINT REFERENCES public.classes(id) ON DELETE CASCADE,
    eleve_id BIGINT REFERENCES public.eleves(id) ON DELETE CASCADE,
    type_eval TEXT DEFAULT 'Évaluation', -- 'Devoir', 'Évaluation', 'Composition'
    date TEXT DEFAULT '',
    bareme NUMERIC DEFAULT 20,
    note NUMERIC NOT NULL,
    coef NUMERIC DEFAULT 1,
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);
ALTER TABLE public.notes ADD COLUMN IF NOT EXISTS type_eval TEXT DEFAULT 'Évaluation';
ALTER TABLE public.notes ADD COLUMN IF NOT EXISTS coef NUMERIC DEFAULT 1;

-- 5. TABLE DES RESSOURCES PÉDAGOGIQUES
CREATE TABLE IF NOT EXISTS public.ressources (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titre TEXT NOT NULL,
    type TEXT DEFAULT 'Document',
    mat TEXT DEFAULT 'Biologie',
    classe_id BIGINT REFERENCES public.classes(id) ON DELETE SET NULL,
    desc_txt TEXT DEFAULT '',
    url_drive TEXT DEFAULT '',
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);
ALTER TABLE public.ressources ADD COLUMN IF NOT EXISTS url_drive TEXT DEFAULT '';

-- 6. TABLE DE L'EMPLOI DU TEMPS (CRÉNEAUX / SLOTS)
CREATE TABLE IF NOT EXISTS public.edt_slots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    jour TEXT NOT NULL,
    hdeb TEXT NOT NULL,
    hfin TEXT NOT NULL,
    mat TEXT NOT NULL,
    classe TEXT NOT NULL,
    lecon TEXT DEFAULT '',
    salle TEXT DEFAULT '',
    span INTEGER DEFAULT 1,
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- 7. TABLE DES RAPPELS
CREATE TABLE IF NOT EXISTS public.rappels (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date TEXT NOT NULL,
    mat TEXT NOT NULL,
    classe TEXT NOT NULL,
    lecon TEXT DEFAULT '',
    canal TEXT DEFAULT 'Navigateur',
    ok BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- 8. TABLE DE CONFIGURATION
CREATE TABLE IF NOT EXISTS public.app_config (
    id TEXT PRIMARY KEY DEFAULT 'general',
    email TEXT DEFAULT 'abdoulkarimdiop77@gmail.com',
    ejs_service TEXT DEFAULT '',
    ejs_template TEXT DEFAULT '',
    ejs_pub_key TEXT DEFAULT '',
    updated_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- 9. NOUVELLE TABLE : REGISTRE DES PRÉSENCES (Octobre 2026 - Juin 2027)
CREATE TABLE IF NOT EXISTS public.presences (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    classe_id BIGINT REFERENCES public.classes(id) ON DELETE CASCADE,
    eleve_id BIGINT REFERENCES public.eleves(id) ON DELETE CASCADE,
    date TEXT NOT NULL, -- YYYY-MM-DD
    seance TEXT DEFAULT '',
    statut TEXT DEFAULT 'P', -- 'P' (Présent), 'A' (Absent), 'R' (Retard)
    motif TEXT DEFAULT '',
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- 10. NOUVELLE TABLE : PLANIFICATION ANNUELLE DU PROGRAMME
CREATE TABLE IF NOT EXISTS public.planifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    classe_id BIGINT REFERENCES public.classes(id) ON DELETE CASCADE,
    mat TEXT NOT NULL,
    trimestre TEXT DEFAULT 'Trimestre 1',
    mois TEXT DEFAULT 'Octobre',
    chapitre TEXT NOT NULL,
    objectifs TEXT DEFAULT '',
    volume_h INTEGER DEFAULT 4,
    statut TEXT DEFAULT 'Prévu', -- 'Prévu', 'En cours', 'Terminé'
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- 11. NOUVELLE TABLE : CAHIER JOURNAL
CREATE TABLE IF NOT EXISTS public.cahier_journal (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    classe_id BIGINT REFERENCES public.classes(id) ON DELETE CASCADE,
    mat TEXT NOT NULL,
    date TEXT NOT NULL,
    seance TEXT DEFAULT '',
    titre_lecon TEXT NOT NULL,
    obj TEXT DEFAULT '',
    obs TEXT DEFAULT '',
    devoirs TEXT DEFAULT '',
    valide BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- 12. NOUVELLE TABLE : DEVOIRS EN LIGNE (TOUS LES CYCLES)
CREATE TABLE IF NOT EXISTS public.devoirs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titre TEXT NOT NULL,
    cycle TEXT DEFAULT 'Collège',
    classe_id BIGINT REFERENCES public.classes(id) ON DELETE CASCADE,
    mat TEXT NOT NULL,
    type_devoir TEXT DEFAULT 'QCM + Questions', -- 'QCM + Questions', 'Sujet Fichier / Drive'
    date_limite TEXT DEFAULT '',
    consignes TEXT DEFAULT '',
    code_acces TEXT DEFAULT '',
    url_sujet TEXT DEFAULT '',
    questions JSONB DEFAULT '[]'::jsonb,
    active BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- 13. NOUVELLE TABLE : RÉPONSES AUX DEVOIRS EN LIGNE
CREATE TABLE IF NOT EXISTS public.devoirs_reponses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    devoir_id BIGINT REFERENCES public.devoirs(id) ON DELETE CASCADE,
    eleve_nom TEXT NOT NULL,
    eleve_matricule TEXT DEFAULT '',
    reponses JSONB DEFAULT '[]'::jsonb,
    note_qcm NUMERIC DEFAULT 0,
    note_ouverte NUMERIC DEFAULT 0,
    note_totale NUMERIC DEFAULT 0,
    bareme_total NUMERIC DEFAULT 20,
    date_soumission TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- INDEXES
CREATE INDEX IF NOT EXISTS idx_eleves_classe ON public.eleves(classe_id);
CREATE INDEX IF NOT EXISTS idx_cours_classe ON public.cours(classe_id);
CREATE INDEX IF NOT EXISTS idx_notes_classe ON public.notes(classe_id);
CREATE INDEX IF NOT EXISTS idx_notes_eleve ON public.notes(eleve_id);
CREATE INDEX IF NOT EXISTS idx_presences_classe ON public.presences(classe_id);
CREATE INDEX IF NOT EXISTS idx_presences_date ON public.presences(date);
CREATE INDEX IF NOT EXISTS idx_cahier_classe ON public.cahier_journal(classe_id);
CREATE INDEX IF NOT EXISTS idx_planif_classe ON public.planifications(classe_id);
CREATE INDEX IF NOT EXISTS idx_devoirs_classe ON public.devoirs(classe_id);
CREATE INDEX IF NOT EXISTS idx_reponses_devoir ON public.devoirs_reponses(devoir_id);

