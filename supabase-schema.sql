-- ==============================================================================
-- INDEX POUR ACCÉLÉRER LES RECHERCHES
-- ==============================================================================
CREATE INDEX IF NOT EXISTS idx_eleves_classe ON public.eleves(classe_id);
CREATE INDEX IF NOT EXISTS idx_cours_classe ON public.cours(classe_id);
CREATE INDEX IF NOT EXISTS idx_notes_classe ON public.notes(classe_id);
CREATE INDEX IF NOT EXISTS idx_notes_eleve ON public.notes(eleve_id);
CREATE INDEX IF NOT EXISTS idx_ressources_classe ON public.ressources(classe_id);
CREATE INDEX IF NOT EXISTS idx_edt_jour ON public.edt_slots(jour);

-- ==============================================================================
-- ROW LEVEL SECURITY (RLS) - SÉCURITÉ D'ACCÈS
-- Permet à l'application web d'effectuer des requêtes avec la clé ANON
-- ==============================================================================
ALTER TABLE public.classes ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.eleves ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.cours ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.notes ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.ressources ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.edt_slots ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.rappels ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.app_config ENABLE ROW LEVEL SECURITY;

-- Politiques ouvertes pour la clé publique anon
DO $$
BEGIN
    DROP POLICY IF EXISTS "Accès public classes" ON public.classes;
    CREATE POLICY "Accès public classes" ON public.classes FOR ALL USING (true) WITH CHECK (true);

    DROP POLICY IF EXISTS "Accès public eleves" ON public.eleves;
    CREATE POLICY "Accès public eleves" ON public.eleves FOR ALL USING (true) WITH CHECK (true);

    DROP POLICY IF EXISTS "Accès public cours" ON public.cours;
    CREATE POLICY "Accès public cours" ON public.cours FOR ALL USING (true) WITH CHECK (true);

    DROP POLICY IF EXISTS "Accès public notes" ON public.notes;
    CREATE POLICY "Accès public notes" ON public.notes FOR ALL USING (true) WITH CHECK (true);

    DROP POLICY IF EXISTS "Accès public ressources" ON public.ressources;
    CREATE POLICY "Accès public ressources" ON public.ressources FOR ALL USING (true) WITH CHECK (true);

    DROP POLICY IF EXISTS "Accès public edt_slots" ON public.edt_slots;
    CREATE POLICY "Accès public edt_slots" ON public.edt_slots FOR ALL USING (true) WITH CHECK (true);

    DROP POLICY IF EXISTS "Accès public rappels" ON public.rappels;
    CREATE POLICY "Accès public rappels" ON public.rappels FOR ALL USING (true) WITH CHECK (true);

    DROP POLICY IF EXISTS "Accès public app_config" ON public.app_config;
    CREATE POLICY "Accès public app_config" ON public.app_config FOR ALL USING (true) WITH CHECK (true);
END
$$;

-- ==============================================================================
-- ACTIVATION DE SUPABASE REALTIME (Synchronisation en temps réel)
-- Permet la mise à jour automatique entre smartphone et ordinateur !
-- ==============================================================================
DO $$
BEGIN
    ALTER PUBLICATION supabase_realtime ADD TABLE public.classes;
    ALTER PUBLICATION supabase_realtime ADD TABLE public.eleves;
    ALTER PUBLICATION supabase_realtime ADD TABLE public.cours;
    ALTER PUBLICATION supabase_realtime ADD TABLE public.notes;
    ALTER PUBLICATION supabase_realtime ADD TABLE public.ressources;
    ALTER PUBLICATION supabase_realtime ADD TABLE public.edt_slots;
    ALTER PUBLICATION supabase_realtime ADD TABLE public.rappels;
    ALTER PUBLICATION supabase_realtime ADD TABLE public.app_config;
EXCEPTION
    WHEN duplicate_object THEN NULL;
    WHEN undefined_object THEN NULL;
END
$$;
